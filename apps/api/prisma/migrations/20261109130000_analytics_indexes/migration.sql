-- Indexes for the analytics dashboard, chosen with EXPLAIN ANALYZE on a million tasks
-- (docs/PERFORMANCE.md).
--
-- Partial: each holds only the slice of rows one part of the dashboard reads (open work, done
-- work), so it is smaller than the table and only the writes that touch that slice maintain it.
-- Covering: the key holds every column those queries read, so Postgres can answer from the index
-- alone ("index-only scan") instead of visiting each row in the table.
--
-- tasks_open_work_idx starts with (organizationId, dueDate), so it also serves "overdue tasks of
-- this organization" (the task list's overdue filter) as a range scan.
--
-- Generated by `prisma migrate diff` from the @@index declarations in schema.prisma.

-- CreateIndex
CREATE INDEX "tasks_open_work_idx" ON "tasks"("organizationId", "dueDate", "status", "projectId", "assigneeId") WHERE ("deletedAt" IS NULL AND status <> 'DONE'::"TaskStatus");

-- CreateIndex
CREATE INDEX "tasks_completed_idx" ON "tasks"("organizationId", "completedAt", "createdAt", "projectId", "assigneeId") WHERE ("deletedAt" IS NULL AND "completedAt" IS NOT NULL);
